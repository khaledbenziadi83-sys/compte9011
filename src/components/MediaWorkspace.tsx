import React, { useState } from 'react';
import { Download, Check, Film, Music, Subtitles, Image as ImageIcon, ListChecks } from 'lucide-react';
import { PlatformLogo } from './PlatformLogo';

import thumbNature from '../assets/images/thumb_cinematic_nature_1791793220729.jpg';
import thumbSynth from '../assets/images/thumb_studio_synth_1791793235548.jpg';
import thumbArch from '../assets/images/thumb_arch_pavilion_1791793246605.jpg';

export interface VideoFormatItem {
  formatId: string;
  label: string;
  ext: string;
  resolution: string;
  quality: string;
  fps: number;
  vcodec: string;
  acodec: string;
  filesizeMb: number;
  watermarkFree?: boolean;
}

export interface AudioFormatItem {
  formatId: string;
  label: string;
  ext: string;
  bitrate: string;
  codec: string;
  sampleRate: string;
  filesizeMb: number;
}

export interface SubtitleItem {
  langCode: string;
  language: string;
  ext: string;
  autoGenerated: boolean;
}

export interface PlaylistEntry {
  id: string;
  index: number;
  title: string;
  durationSeconds: number;
  resolution: string;
  filesizeMb: number;
}

export interface ExtractedMediaInfo {
  id: string;
  url: string;
  title: string;
  uploader: string;
  durationSeconds: number;
  thumbnail: string | null;
  platform: {
    id: string;
    name: string;
    category: string;
    supportsNoWatermark?: boolean;
    contentTypeLabel?: string;
  };
  isPlaylist: boolean;
  playlistItems: PlaylistEntry[];
  videoFormats: VideoFormatItem[];
  audioFormats: AudioFormatItem[];
  subtitles: SubtitleItem[];
  extractedAt: string;
}

interface MediaWorkspaceProps {
  media: ExtractedMediaInfo;
}

function formatDuration(totalSeconds: number): string {
  const hrs = Math.floor(totalSeconds / 3600);
  const mins = Math.floor((totalSeconds % 3600) / 60);
  const secs = Math.floor(totalSeconds % 60);
  if (hrs > 0) {
    return `${hrs}:${String(mins).padStart(2, '0')}:${String(secs).padStart(2, '0')}`;
  }
  return `${String(mins).padStart(2, '0')}:${String(secs).padStart(2, '0')}`;
}

export const MediaWorkspace: React.FC<MediaWorkspaceProps> = ({ media }) => {
  const defaultTab = media.videoFormats.length > 0 ? 'video' : 'audio';
  const [activeTab, setActiveTab] = useState<'video' | 'audio' | 'subtitles' | 'thumbnail' | 'playlist'>(
    media.isPlaylist ? 'playlist' : defaultTab
  );
  const [imgError, setImgError] = useState(false);
  const [activeDownloadId, setActiveDownloadId] = useState<string | null>(null);
  const [downloadProgress, setDownloadProgress] = useState<number>(0);
  const [completedDownloads, setCompletedDownloads] = useState<Record<string, boolean>>({});
  const [selectedPlaylistIds, setSelectedPlaylistIds] = useState<string[]>(
    media.playlistItems.map((item) => item.id)
  );
  const [videoContainerFilter, setVideoContainerFilter] = useState<'all' | 'mp4' | 'webm'>('all');

  // Choose domain-authentic studio fallback image based on platform category
  const fallbackImage =
    media.platform.category === 'Audio'
      ? thumbSynth
      : media.platform.id === 'instagram' || media.platform.id === 'pinterest'
      ? thumbArch
      : thumbNature;

  const displayThumbnail = !imgError && media.thumbnail ? media.thumbnail : fallbackImage;

  const triggerStreamDownload = async (params: {
    downloadKey: string;
    type: 'video' | 'audio' | 'subtitle' | 'thumbnail';
    ext: string;
    quality: string;
    title?: string;
    lang?: string;
  }) => {
    if (activeDownloadId) return;
    setActiveDownloadId(params.downloadKey);
    setDownloadProgress(12);

    try {
      const query = new URLSearchParams({
        url: media.url,
        type: params.type,
        ext: params.ext,
        quality: params.quality,
        title: params.title || media.title,
        ...(params.lang ? { lang: params.lang } : {}),
      });

      const response = await fetch(`/api/download?${query.toString()}`);
      if (!response.ok) {
        throw new Error('Download stream failed');
      }

      const contentLength = Number(response.headers.get('Content-Length')) || 131072;
      const reader = response.body?.getReader();
      const chunks: Uint8Array[] = [];
      let receivedLength = 0;

      if (reader) {
        while (true) {
          const { done, value } = await reader.read();
          if (done) break;
          if (value) {
            chunks.push(value);
            receivedLength += value.length;
            const pct = Math.min(96, Math.round((receivedLength / contentLength) * 100));
            setDownloadProgress(pct);
          }
        }
      }

      setDownloadProgress(100);
      const blob = new Blob(chunks, {
        type: response.headers.get('Content-Type') || 'application/octet-stream',
      });
      const blobUrl = URL.createObjectURL(blob);
      const safeTitle = (params.title || media.title)
        .toLowerCase()
        .replace(/[^a-z0-9]+/g, '_')
        .replace(/^_+|_+$/g, '')
        .slice(0, 48) || 'velofetch_media';

      const anchor = document.createElement('a');
      anchor.href = blobUrl;
      anchor.download = `${safeTitle}_${params.quality.replace(/[^a-z0-9]/gi, '')}.${params.ext}`;
      document.body.appendChild(anchor);
      anchor.click();
      document.body.removeChild(anchor);
      setTimeout(() => URL.revokeObjectURL(blobUrl), 5000);

      setCompletedDownloads((prev) => ({ ...prev, [params.downloadKey]: true }));
    } catch {
      // Fallback direct navigation if stream reader interrupted
      const query = new URLSearchParams({
        url: media.url,
        type: params.type,
        ext: params.ext,
        quality: params.quality,
        title: params.title || media.title,
      });
      const anchor = document.createElement('a');
      anchor.href = `/api/download?${query.toString()}`;
      anchor.download = '';
      document.body.appendChild(anchor);
      anchor.click();
      document.body.removeChild(anchor);
      setCompletedDownloads((prev) => ({ ...prev, [params.downloadKey]: true }));
    } finally {
      setTimeout(() => {
        setActiveDownloadId(null);
        setDownloadProgress(0);
      }, 450);
    }
  };

  const togglePlaylistItem = (id: string) => {
    setSelectedPlaylistIds((prev) =>
      prev.includes(id) ? prev.filter((item) => item !== id) : [...prev, id]
    );
  };

  const filteredVideoFormats = media.videoFormats.filter((f) =>
    videoContainerFilter === 'all' ? true : f.ext.toLowerCase() === videoContainerFilter
  );

  return (
    <section
      aria-label="Extracted Media Download Options"
      className="mt-8 border border-slate-200 dark:border-slate-800 bg-white dark:bg-slate-900/90 rounded-xl overflow-hidden"
    >
      {/* Top Media Identity Row */}
      <div className="grid grid-cols-1 lg:grid-cols-12 border-b border-slate-200 dark:border-slate-800">
        {/* Thumbnail Preview with Measured Scrim */}
        <div className="lg:col-span-5 relative bg-slate-950 min-h-[220px] lg:min-h-full overflow-hidden">
          <img
            src={displayThumbnail}
            alt={media.title}
            referrerPolicy="no-referrer"
            onError={() => setImgError(true)}
            className="w-full h-full object-cover"
          />
          <div className="absolute inset-0 bg-gradient-to-t from-black/80 via-black/25 to-transparent flex flex-col justify-end p-5">
            <div className="flex items-center gap-2 text-xs text-slate-200 font-mono tabular-nums">
              <span>{media.platform.name}</span>
              <span aria-hidden="true">·</span>
              <span>Duration {formatDuration(media.durationSeconds)}</span>
              {media.platform.supportsNoWatermark && (
                <>
                  <span aria-hidden="true">·</span>
                  <span>Watermark-Free Ready</span>
                </>
              )}
            </div>
          </div>
        </div>

        {/* Metadata & Format Switcher Column */}
        <div className="lg:col-span-7 p-6 lg:p-8 flex flex-col justify-between">
          <div>
            <div className="flex items-center gap-2 text-xs text-slate-500 dark:text-slate-400 mb-2">
              <PlatformLogo id={media.platform.id} className="w-4 h-4" />
              <span>{media.platform.name}</span>
              <span aria-hidden="true">·</span>
              <span>{media.platform.contentTypeLabel || 'Direct Stream'}</span>
              <span aria-hidden="true">·</span>
              <span>Uploader: {media.uploader}</span>
            </div>

            <h2 className="text-xl lg:text-2xl font-bold text-slate-900 dark:text-white tracking-tight leading-snug">
              {media.title}
            </h2>

            <div className="mt-3 flex flex-wrap items-center gap-x-3 gap-y-1 text-xs text-slate-500 dark:text-slate-400 font-mono tabular-nums">
              <span>ID: {media.id}</span>
              <span aria-hidden="true">·</span>
              <span>Length: {formatDuration(media.durationSeconds)}</span>
              <span aria-hidden="true">·</span>
              <span>{media.videoFormats.length} Video Presets</span>
              <span aria-hidden="true">·</span>
              <span>{media.audioFormats.length} Audio Presets</span>
              <span aria-hidden="true">·</span>
              <span>{media.subtitles.length} Subtitle Tracks</span>
            </div>
          </div>

          {/* Interactive Stream Progress Indicator */}
          {activeDownloadId && (
            <div className="mt-5 pt-4 border-t border-slate-100 dark:border-slate-800" role="status" aria-live="polite">
              <div className="flex items-center justify-between text-xs font-mono tabular-nums text-blue-600 dark:text-blue-400 mb-1.5">
                <span>Muxing &amp; streaming file to browser...</span>
                <span>{downloadProgress}%</span>
              </div>
              <div className="w-full h-1.5 bg-slate-100 dark:bg-slate-800 rounded-full overflow-hidden">
                <div
                  className="h-full bg-blue-600 transition-transform duration-150 origin-left"
                  style={{ transform: `scaleX(${downloadProgress / 100})` }}
                />
              </div>
            </div>
          )}

          {/* Segmented Format Category Controls */}
          <div className="mt-6 pt-5 border-t border-slate-200 dark:border-slate-800 flex flex-wrap items-center gap-1.5">
            {media.isPlaylist && (
              <button
                type="button"
                onClick={() => setActiveTab('playlist')}
                className={`inline-flex items-center gap-2 px-3.5 py-2 text-xs font-medium rounded-lg transition-colors whitespace-nowrap shrink-0 ${
                  activeTab === 'playlist'
                    ? 'bg-blue-600 text-white'
                    : 'bg-slate-100 dark:bg-slate-800 text-slate-700 dark:text-slate-300 hover:bg-slate-200 dark:hover:bg-slate-700'
                }`}
              >
                <ListChecks className="w-3.5 h-3.5" />
                <span>Playlist Items ({media.playlistItems.length})</span>
              </button>
            )}

            {media.videoFormats.length > 0 && (
              <button
                type="button"
                onClick={() => setActiveTab('video')}
                className={`inline-flex items-center gap-2 px-3.5 py-2 text-xs font-medium rounded-lg transition-colors whitespace-nowrap shrink-0 ${
                  activeTab === 'video'
                    ? 'bg-blue-600 text-white'
                    : 'bg-slate-100 dark:bg-slate-800 text-slate-700 dark:text-slate-300 hover:bg-slate-200 dark:hover:bg-slate-700'
                }`}
              >
                <Film className="w-3.5 h-3.5" />
                <span>Video ({media.videoFormats.length})</span>
              </button>
            )}

            <button
              type="button"
              onClick={() => setActiveTab('audio')}
              className={`inline-flex items-center gap-2 px-3.5 py-2 text-xs font-medium rounded-lg transition-colors whitespace-nowrap shrink-0 ${
                activeTab === 'audio'
                  ? 'bg-blue-600 text-white'
                  : 'bg-slate-100 dark:bg-slate-800 text-slate-700 dark:text-slate-300 hover:bg-slate-200 dark:hover:bg-slate-700'
              }`}
            >
              <Music className="w-3.5 h-3.5" />
              <span>Audio Only ({media.audioFormats.length})</span>
            </button>

            <button
              type="button"
              onClick={() => setActiveTab('subtitles')}
              className={`inline-flex items-center gap-2 px-3.5 py-2 text-xs font-medium rounded-lg transition-colors whitespace-nowrap shrink-0 ${
                activeTab === 'subtitles'
                  ? 'bg-blue-600 text-white'
                  : 'bg-slate-100 dark:bg-slate-800 text-slate-700 dark:text-slate-300 hover:bg-slate-200 dark:hover:bg-slate-700'
              }`}
            >
              <Subtitles className="w-3.5 h-3.5" />
              <span>Subtitles ({media.subtitles.length})</span>
            </button>

            <button
              type="button"
              onClick={() => setActiveTab('thumbnail')}
              className={`inline-flex items-center gap-2 px-3.5 py-2 text-xs font-medium rounded-lg transition-colors whitespace-nowrap shrink-0 ${
                activeTab === 'thumbnail'
                  ? 'bg-blue-600 text-white'
                  : 'bg-slate-100 dark:bg-slate-800 text-slate-700 dark:text-slate-300 hover:bg-slate-200 dark:hover:bg-slate-700'
              }`}
            >
              <ImageIcon className="w-3.5 h-3.5" />
              <span>Thumbnail</span>
            </button>
          </div>
        </div>
      </div>

      {/* Tab Content Area: High-Density Data Table */}
      <div className="p-6 lg:p-8">
        {activeTab === 'video' && (
          <div>
            <div className="flex flex-wrap items-center justify-between gap-4 mb-4">
              <div className="text-xs text-slate-500 dark:text-slate-400">
                Select resolution and container format (MP4 H.264/AV1 or WebM VP9)
              </div>
              <div className="flex items-center gap-1 p-1 bg-slate-100 dark:bg-slate-800 rounded-lg">
                {(['all', 'mp4', 'webm'] as const).map((container) => (
                  <button
                    key={container}
                    type="button"
                    onClick={() => setVideoContainerFilter(container)}
                    className={`px-3 py-1 text-xs font-medium rounded-md transition-colors whitespace-nowrap shrink-0 ${
                      videoContainerFilter === container
                        ? 'bg-white dark:bg-slate-900 text-slate-900 dark:text-white shadow-xs'
                        : 'text-slate-600 dark:text-slate-400 hover:text-slate-900 dark:hover:text-white'
                    }`}
                  >
                    {container === 'all' ? 'All Containers' : container.toUpperCase()}
                  </button>
                ))}
              </div>
            </div>

            <div className="overflow-x-auto">
              <table className="w-full text-left border-collapse">
                <thead>
                  <tr className="border-b border-slate-200 dark:border-slate-800 text-xs font-medium text-slate-500 dark:text-slate-400">
                    <th className="py-3 pr-4">Quality &amp; Preset</th>
                    <th className="py-3 px-4">Container</th>
                    <th className="py-3 px-4">Resolution · FPS</th>
                    <th className="py-3 px-4">Video / Audio Codecs</th>
                    <th className="py-3 px-4 text-right">Est. Size</th>
                    <th className="py-3 pl-4 text-right">Action</th>
                  </tr>
                </thead>
                <tbody className="divide-y divide-slate-200/70 dark:divide-slate-800/70 text-sm">
                  {filteredVideoFormats.map((item) => {
                    const isDownloading = activeDownloadId === item.formatId;
                    const isDone = completedDownloads[item.formatId];
                    return (
                      <tr
                        key={item.formatId}
                        className="hover:bg-slate-50/80 dark:hover:bg-slate-800/40 transition-colors"
                      >
                        <td className="py-3.5 pr-4 font-medium text-slate-900 dark:text-white">
                          <span>{item.label}</span>
                          {media.platform.supportsNoWatermark && item.watermarkFree && (
                            <span className="ml-2 text-xs text-emerald-600 dark:text-emerald-400 font-normal">
                              · Clean Source
                            </span>
                          )}
                        </td>
                        <td className="py-3.5 px-4 font-mono text-xs uppercase text-slate-600 dark:text-slate-300">
                          {item.ext}
                        </td>
                        <td className="py-3.5 px-4 font-mono tabular-nums text-xs text-slate-600 dark:text-slate-300">
                          {item.resolution} · {item.fps}fps
                        </td>
                        <td className="py-3.5 px-4 font-mono text-xs text-slate-500 dark:text-slate-400">
                          {item.vcodec} / {item.acodec}
                        </td>
                        <td className="py-3.5 px-4 text-right font-mono tabular-nums text-xs text-slate-600 dark:text-slate-300">
                          {item.filesizeMb.toFixed(1)} MB
                        </td>
                        <td className="py-3.5 pl-4 text-right">
                          <button
                            type="button"
                            disabled={Boolean(activeDownloadId)}
                            onClick={() =>
                              triggerStreamDownload({
                                downloadKey: item.formatId,
                                type: 'video',
                                ext: item.ext,
                                quality: item.quality,
                              })
                            }
                            className="inline-flex items-center gap-1.5 px-4 py-2 text-xs font-medium text-white bg-blue-600 hover:bg-blue-700 disabled:opacity-50 rounded-lg transition-colors whitespace-nowrap shrink-0 cursor-pointer"
                          >
                            {isDownloading ? (
                              <span>Streaming...</span>
                            ) : isDone ? (
                              <>
                                <Check className="w-3.5 h-3.5" />
                                <span>Saved .{item.ext}</span>
                              </>
                            ) : (
                              <>
                                <Download className="w-3.5 h-3.5" />
                                <span>Download .{item.ext.toUpperCase()}</span>
                              </>
                            )}
                          </button>
                        </td>
                      </tr>
                    );
                  })}
                </tbody>
              </table>
            </div>
          </div>
        )}

        {activeTab === 'audio' && (
          <div className="overflow-x-auto">
            <table className="w-full text-left border-collapse">
              <thead>
                <tr className="border-b border-slate-200 dark:border-slate-800 text-xs font-medium text-slate-500 dark:text-slate-400">
                  <th className="py-3 pr-4">Audio Preset</th>
                  <th className="py-3 px-4">Format</th>
                  <th className="py-3 px-4">Bitrate · Sample Rate</th>
                  <th className="py-3 px-4">Encoder</th>
                  <th className="py-3 px-4 text-right">Est. Size</th>
                  <th className="py-3 pl-4 text-right">Action</th>
                </tr>
              </thead>
              <tbody className="divide-y divide-slate-200/70 dark:divide-slate-800/70 text-sm">
                {media.audioFormats.map((audio) => {
                  const isDownloading = activeDownloadId === audio.formatId;
                  const isDone = completedDownloads[audio.formatId];
                  return (
                    <tr
                      key={audio.formatId}
                      className="hover:bg-slate-50/80 dark:hover:bg-slate-800/40 transition-colors"
                    >
                      <td className="py-3.5 pr-4 font-medium text-slate-900 dark:text-white">
                        {audio.label}
                      </td>
                      <td className="py-3.5 px-4 font-mono text-xs uppercase text-slate-600 dark:text-slate-300">
                        {audio.ext}
                      </td>
                      <td className="py-3.5 px-4 font-mono tabular-nums text-xs text-slate-600 dark:text-slate-300">
                        {audio.bitrate} · {audio.sampleRate}
                      </td>
                      <td className="py-3.5 px-4 font-mono text-xs text-slate-500 dark:text-slate-400">
                        {audio.codec}
                      </td>
                      <td className="py-3.5 px-4 text-right font-mono tabular-nums text-xs text-slate-600 dark:text-slate-300">
                        {audio.filesizeMb.toFixed(1)} MB
                      </td>
                      <td className="py-3.5 pl-4 text-right">
                        <button
                          type="button"
                          disabled={Boolean(activeDownloadId)}
                          onClick={() =>
                            triggerStreamDownload({
                              downloadKey: audio.formatId,
                              type: 'audio',
                              ext: audio.ext,
                              quality: audio.bitrate.split(' ')[0] + 'kbps',
                            })
                          }
                          className="inline-flex items-center gap-1.5 px-4 py-2 text-xs font-medium text-white bg-blue-600 hover:bg-blue-700 disabled:opacity-50 rounded-lg transition-colors whitespace-nowrap shrink-0 cursor-pointer"
                        >
                          {isDownloading ? (
                            <span>Extracting...</span>
                          ) : isDone ? (
                            <>
                              <Check className="w-3.5 h-3.5" />
                              <span>Saved .{audio.ext}</span>
                            </>
                          ) : (
                            <>
                              <Download className="w-3.5 h-3.5" />
                              <span>Download .{audio.ext.toUpperCase()}</span>
                            </>
                          )}
                        </button>
                      </td>
                    </tr>
                  );
                })}
              </tbody>
            </table>
          </div>
        )}

        {activeTab === 'subtitles' && (
          <div className="overflow-x-auto">
            <table className="w-full text-left border-collapse">
              <thead>
                <tr className="border-b border-slate-200 dark:border-slate-800 text-xs font-medium text-slate-500 dark:text-slate-400">
                  <th className="py-3 pr-4">Language Track</th>
                  <th className="py-3 px-4">Track Type</th>
                  <th className="py-3 px-4">Format</th>
                  <th className="py-3 pl-4 text-right">Action</th>
                </tr>
              </thead>
              <tbody className="divide-y divide-slate-200/70 dark:divide-slate-800/70 text-sm">
                {media.subtitles.map((sub) => {
                  const subKey = `sub-${sub.langCode}-${sub.ext}`;
                  const isDone = completedDownloads[subKey];
                  return (
                    <tr
                      key={subKey}
                      className="hover:bg-slate-50/80 dark:hover:bg-slate-800/40 transition-colors"
                    >
                      <td className="py-3.5 pr-4 font-medium text-slate-900 dark:text-white">
                        {sub.language}
                      </td>
                      <td className="py-3.5 px-4 text-xs text-slate-500 dark:text-slate-400">
                        {sub.autoGenerated ? 'Auto-Synced Transcript' : 'Creator Closed Captions (CC)'}
                      </td>
                      <td className="py-3.5 px-4 font-mono text-xs uppercase text-slate-600 dark:text-slate-300">
                        .{sub.ext}
                      </td>
                      <td className="py-3.5 pl-4 text-right">
                        <button
                          type="button"
                          disabled={Boolean(activeDownloadId)}
                          onClick={() =>
                            triggerStreamDownload({
                              downloadKey: subKey,
                              type: 'subtitle',
                              ext: sub.ext,
                              quality: sub.langCode,
                              lang: sub.langCode,
                            })
                          }
                          className="inline-flex items-center gap-1.5 px-4 py-2 text-xs font-medium text-slate-900 dark:text-white bg-slate-100 dark:bg-slate-800 hover:bg-slate-200 dark:hover:bg-slate-700 rounded-lg transition-colors whitespace-nowrap shrink-0 cursor-pointer"
                        >
                          {isDone ? (
                            <>
                              <Check className="w-3.5 h-3.5 text-emerald-600" />
                              <span>Downloaded .{sub.ext}</span>
                            </>
                          ) : (
                            <>
                              <Download className="w-3.5 h-3.5" />
                              <span>Save .{sub.ext.toUpperCase()}</span>
                            </>
                          )}
                        </button>
                      </td>
                    </tr>
                  );
                })}
              </tbody>
            </table>
          </div>
        )}

        {activeTab === 'thumbnail' && (
          <div className="flex flex-col md:flex-row items-start md:items-center justify-between gap-6">
            <div className="space-y-1">
              <h3 className="text-base font-semibold text-slate-900 dark:text-white">
                Maximum Resolution Cover Frame
              </h3>
              <p className="text-xs text-slate-500 dark:text-slate-400 font-mono tabular-nums">
                1920×1080 JPEG · sRGB Color Profile · Uncompressed Frame Still
              </p>
            </div>
            <button
              type="button"
              disabled={Boolean(activeDownloadId)}
              onClick={() =>
                triggerStreamDownload({
                  downloadKey: 'thumb-maxres',
                  type: 'thumbnail',
                  ext: 'jpg',
                  quality: 'maxresdefault',
                })
              }
              className="inline-flex items-center gap-2 px-5 py-2.5 text-xs font-medium text-white bg-blue-600 hover:bg-blue-700 rounded-lg transition-colors whitespace-nowrap shrink-0 cursor-pointer"
            >
              <Download className="w-4 h-4" />
              <span>Download Max-Res Thumbnail (.JPG)</span>
            </button>
          </div>
        )}

        {activeTab === 'playlist' && media.isPlaylist && (
          <div>
            <div className="flex flex-wrap items-center justify-between gap-4 mb-4">
              <div className="text-xs text-slate-600 dark:text-slate-300 font-mono tabular-nums">
                Selected {selectedPlaylistIds.length} of {media.playlistItems.length} items in collection
              </div>
              <div className="flex items-center gap-2">
                <button
                  type="button"
                  onClick={() =>
                    setSelectedPlaylistIds(
                      selectedPlaylistIds.length === media.playlistItems.length
                        ? []
                        : media.playlistItems.map((i) => i.id)
                    )
                  }
                  className="px-3 py-1.5 text-xs font-medium text-slate-700 dark:text-slate-300 bg-slate-100 dark:bg-slate-800 hover:bg-slate-200 dark:hover:bg-slate-700 rounded-lg transition-colors whitespace-nowrap shrink-0 cursor-pointer"
                >
                  {selectedPlaylistIds.length === media.playlistItems.length ? 'Deselect All' : 'Select All'}
                </button>
                <button
                  type="button"
                  disabled={selectedPlaylistIds.length === 0 || Boolean(activeDownloadId)}
                  onClick={() =>
                    triggerStreamDownload({
                      downloadKey: 'playlist-batch',
                      type: 'video',
                      ext: 'mp4',
                      quality: `batch_${selectedPlaylistIds.length}_items_1080p`,
                      title: `${media.title}_batch`,
                    })
                  }
                  className="inline-flex items-center gap-1.5 px-4 py-1.5 text-xs font-medium text-white bg-blue-600 hover:bg-blue-700 disabled:opacity-50 rounded-lg transition-colors whitespace-nowrap shrink-0 cursor-pointer"
                >
                  <Download className="w-3.5 h-3.5" />
                  <span>Download Selected ({selectedPlaylistIds.length})</span>
                </button>
              </div>
            </div>

            <div className="divide-y divide-slate-200 dark:divide-slate-800 border-t border-slate-200 dark:border-slate-800">
              {media.playlistItems.map((item) => {
                const checked = selectedPlaylistIds.includes(item.id);
                return (
                  <div
                    key={item.id}
                    className="py-3.5 flex items-center justify-between gap-4 hover:bg-slate-50/80 dark:hover:bg-slate-800/40 transition-colors"
                  >
                    <label className="flex items-center gap-3 cursor-pointer flex-1 min-w-0">
                      <input
                        type="checkbox"
                        checked={checked}
                        onChange={() => togglePlaylistItem(item.id)}
                        className="w-4 h-4 rounded border-slate-300 text-blue-600 focus:ring-blue-500"
                      />
                      <span className="text-sm font-medium text-slate-900 dark:text-white truncate">
                        {item.title}
                      </span>
                    </label>
                    <div className="flex items-center gap-4 shrink-0">
                      <span className="text-xs font-mono tabular-nums text-slate-500 dark:text-slate-400">
                        {formatDuration(item.durationSeconds)} · {item.resolution} · {item.filesizeMb} MB
                      </span>
                      <button
                        type="button"
                        onClick={() =>
                          triggerStreamDownload({
                            downloadKey: item.id,
                            type: 'video',
                            ext: 'mp4',
                            quality: '1080p',
                            title: item.title,
                          })
                        }
                        className="px-3 py-1.5 text-xs font-medium text-slate-900 dark:text-white bg-slate-100 dark:bg-slate-800 hover:bg-slate-200 dark:hover:bg-slate-700 rounded-lg transition-colors whitespace-nowrap shrink-0 cursor-pointer"
                      >
                        Save MP4
                      </button>
                    </div>
                  </div>
                );
              })}
            </div>
          </div>
        )}
      </div>
    </section>
  );
};
